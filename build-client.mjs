// Build the hand-written client bundle from ordered source fragments.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const parts = ['state.js', 'context.js', 'style.js', 'execution.js', 'explorer.js', 'canvas.js', 'conversations.js', 'preview.js', 'inspector.js', 'delivery-style.js', 'assistant.js', 'maintenance.js', 'panel.js', 'entry.js'];
const sharedModel = fs.readFileSync(path.join(dir, 'board-model.js'), 'utf8').replace(/^export\s+(?=function|const|let|var)/gm, '');
const bodies = [sharedModel, ...parts.map((name) => fs.readFileSync(path.join(dir, 'client-src', name), 'utf8'))];
const bundle = [
  '// dsh-project-board browser bundle (generated by build-client.mjs).',
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-project-board',",
  '  factory(require) {',
  "    const React = require('react');",
  "    const { createPortal } = require('react-dom');",
  "    const { MarkdownText, MarkdownDelegateProvider } = require('@deepseek-ai/dsh-client-ui-primitives');",
  bodies.join('\n\n'),
  '  },',
  '});',
  '',
].join('\n');
// 先核验完整产物再发布，避免热加载读到存在语法错误的 bundle。
const syntax = spawnSync(process.execPath, ['--check'], { input: bundle, encoding: 'utf8' });
if (syntax.status !== 0) throw new Error(syntax.stderr || '客户端语法检查失败');
fs.writeFileSync(path.join(dir, 'client.js'), bundle);
console.error(JSON.stringify({ clientBytes: Buffer.byteLength(bundle) }));
